function decodeCanonModelId(reserved){
  return Number.isInteger(reserved)&&reserved>=0&&reserved<=0xffffffff?((reserved^0x31247e3b)>>>0):null;
}
function cameraAccessorySupport(modelId){
  const known=Number.isInteger(modelId)&&KNOWN.has(modelId);
  return {known,flashPopup:known&&FLASH_POPUP.has(modelId),bulbRoute:known?(PRESS_BULB.has(modelId)?'press-shutter':DEDICATED_BULB.has(modelId)?'dedicated':null):null};
}
